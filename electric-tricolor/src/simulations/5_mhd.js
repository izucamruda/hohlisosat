function draw_mhd(ctx, w, h, t, p, oc) { 
    // Глубокий темный фон жидкого субстрата
    ctx.fillStyle = '#020204'; 
    ctx.fillRect(0, 0, w, h); 
    
    // Исправлено: Низкочастотный гул сверхпроводящих магнитов (42 Гц)
    let freq = 42 + Math.sin(t * 0.04) * 3;
    let vol = oc ? 0.6 : 0.25;
    setAudio(freq, vol, 'sine'); 
    
    let sh = h / 3; 
    
    // Рендерим поток жидкого металла волновыми полосами
    for (let y = 10; y < h - 10; y += 4) { 
        // Исправлено: Безопасное определение индекса зоны флага (0, 1, 2)
        let z = Math.min(2, Math.floor(y / sh)); 
        
        // Исправлены строки базовых цветов (оставляем место под альфа-канал)
        let base = ['255,255,255', '0,110,255', '235,20,20'][z]; 
        
        // Исправлено: Амплитуда колебаний магнитного гидро-потока
        let amp = (oc ? 50 : 18) * Math.sin(y * 0.04 + t * 0.08) * p; 
        
        // Исправлено: Расчет прозрачности (эффект бликов на металле)
        let alpha = 0.4 + Math.sin(y * 0.08 + t * 0.15) * 0.3;
        
        // Корректная сборка RGBA строки
        ctx.fillStyle = `rgba(${base}, ${alpha})`;
        
        // Исправлено: amp * 2 вместо amp2
        ctx.fillRect(40 + amp, y, w - 80 - (amp * 2), 3); 
        
        // При сильном разгоне сети добавляем искрящиеся наночастицы в металл
        if (oc && Math.random() < 0.05) {
            ctx.fillStyle = '#fff';
            ctx.fillRect(40 + amp + Math.random() * (w - 80 - amp * 2), y, 2, 2);
        }
    } 
    
    // 2. Визуализация магнитных катушек индукции по бокам (кадр рамки)
    ctx.strokeStyle = oc ? '#ef4444' : '#1b1f38';
    ctx.lineWidth = 2;
    ctx.strokeRect(20, 10, w - 40, h - 20);
}

// Экспортируем функцию для автоматического билдера compile.py
window.draw_mhd = draw_mhd;
